/**
 * Render one responsive Studio featured image.
 *
 * @param WP_Post             $post       CMS record.
 * @param string              $sizes      Responsive sizes value.
 * @param array<string,mixed> $attributes Additional image attributes.
 * @return string
 */
function nice_get_studio_featured_image( $post, $sizes, $attributes = array() ) {
	if ( ! $post instanceof WP_Post || ! function_exists( 'nice_theme_get_featured_image' ) ) {
		return '';
	}

	return nice_theme_get_featured_image( $post->ID, $sizes, $attributes );
}

/**
 * Return only approved, currently available contact actions.
 *
 * @return array<int,array{channel:string,label:string,url:string}>
 */
function nice_get_studio_contact_actions() {
	$labels  = array( 'whatsapp' => 'WhatsApp', 'email' => 'Email', 'phone' => 'Phone' );
	$actions = array();

	foreach ( $labels as $channel => $label ) {
		$action = nice_get_contact_action( $channel, '#studio-contact-pending' );

		if ( ! $action['placeholder'] ) {
			$actions[] = array( 'channel' => $channel, 'label' => $label, 'url' => $action['url'] );
		}
	}

	return $actions;
}

