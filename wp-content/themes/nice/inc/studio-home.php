/**
 * Register the request-time Studio Home block.
 */
function nice_register_studio_home_block() {
	register_block_type(
		'nice/studio-home',
		array(
			'render_callback' => 'nice_render_studio_home',
		)
	);
}
add_action( 'init', 'nice_register_studio_home_block' );
